const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const http = require('node:http');
const root = path.resolve(__dirname,'..');
const temp = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(),'dk-preview-plugin-')));
const project = path.join(temp,'Projeto com espaços'); fs.mkdirSync(project); fs.mkdirSync(path.join(temp,'config'));
const helper = process.env.DK_PLUGIN_PREVIEW_HELPER || path.resolve(root, '..', 'dk', 'cli', 'dk-visualizar');
if (!fs.existsSync(helper)) throw new Error('Defina DK_PLUGIN_PREVIEW_HELPER para o comando dk-visualizar do plugin.');
const server = http.createServer((_req,res)=>res.end('<html><title>Prévia do projeto</title><body>PREVIEW_INTEGRADA_OK</body></html>'));
let app;
(async()=>{
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve)); const port=server.address().port;
 app = await electron.launch({args:[root],env:{...process.env,DK_TERMINAL_TEST:'1',DK_TERMINAL_DATA_DIR:path.join(temp,'config'),DK_TERMINAL_TEST_PROJECT:project},timeout:60000});
 const page=await app.firstWindow(); await page.locator('#startup-loading').waitFor({state:'detached'});
 await page.locator('#launcher-recents .launcher-recent').first().click();
 await page.locator('#new-session').click();
 await page.locator('.terminal-pane[data-ready="true"]').waitFor();
 await page.evaluate(()=>{window.__output='';window.dk.onTerminalData(e=>window.__output+=e.data)});
 const id=(await page.locator('.tab-select[aria-selected="true"]').getAttribute('id')).slice(4);
 const quote = s => "'"+s.replaceAll("'", "'\\''")+"'";
 const invalid=`python3 ${quote(helper)} --projeto ${quote(temp)} --url http://127.0.0.1:${port}/\r`;
 await page.evaluate(({id,command})=>window.dk.writeTerminal(id,command),{id,command:invalid});
 await page.waitForFunction(()=>window.__output.includes('O projeto solicitado não corresponde a esta sessão'),null,{timeout:10000});
 const external=`python3 ${quote(helper)} --projeto ${quote(project)} --url https://example.com/\r`;
 await page.evaluate(({id,command})=>window.dk.writeTerminal(id,command),{id,command:external});
 await page.waitForFunction(()=>window.__output.includes('Não foi possível abrir a prévia no DK Terminal'),null,{timeout:10000});
 const command=`python3 ${quote(helper)} --projeto ${quote(project)} --url http://127.0.0.1:${port}/\r`;
 await page.evaluate(({id,command})=>window.dk.writeTerminal(id,command),{id,command});
 await page.waitForFunction(()=>window.__output.includes('Prévia aberta no navegador do DK Terminal.'),null,{timeout:20000});
 await page.locator('#browser-view').waitFor({state:'visible'});
 assert.equal(await page.locator('#browser-address').inputValue(),`http://127.0.0.1:${port}/`);
 const views=await app.evaluate(async ({BrowserWindow})=>Promise.all(BrowserWindow.getAllWindows()[0].contentView.children.filter(v=>v.webContents).map(async v=>({url:v.webContents.getURL(), body:await v.webContents.executeJavaScript('document.body.textContent')}))));
 assert.ok(views.some(v=>v.url.includes('127.0.0.1:') && v.body.includes('PREVIEW_INTEGRADA_OK')));
 console.log('OK: pedido do plugin abriu a página real no navegador integrado');
})().catch(error=>{console.error(error);process.exitCode=1}).finally(async()=>{if(app) await app.close();server.close();fs.rmSync(temp,{recursive:true,force:true})});
